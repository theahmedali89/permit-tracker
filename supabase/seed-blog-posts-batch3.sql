It depends on the jurisdiction. Some AHJs offer reinstatement or renewal for recently expired permits — Chicago allows reinstatement after 365 days of no inspection, Seattle can reestablish permits expired less than a year. Others, like Philadelphia, require a brand-new permit once expiration has occurred. Ask your specific building department; the answer varies enormously.

