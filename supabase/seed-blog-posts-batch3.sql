Here's the direct answer: **when a building permit expires, the legal authorization to do the work ends.** In most U.S. jurisdictions, continuing construction under an expired permit is treated the same as building with no permit at all. Work must stop, inspections can't proceed, and the building department can issue stop-work orders and fines until the situation is resolved.

How a permit expires, what it costs you, and how you recover all depend on your local Authority Having Jurisdiction (AHJ) — the city or county building department that issued the permit. But the pattern is remarkably consistent across the country, and understanding it is the difference between a minor administrative hiccup and a project-derailing event.

## The 180-Day Rule: Why Most Permits Expire the Same Way

If you take one thing from this article, take this: **most building permits in major U.S. cities expire after 180 days without inspection activity.** Our research across 20 major metros found the 180-day abandonment rule in Los Angeles, Chicago, Phoenix, Philadelphia, San Antonio, Austin, Jacksonville, Fort Worth, Charlotte, and San Francisco — ten of the twenty largest U.S. cities use essentially the same standard.

The rule works like this: once a permit is issued, the clock starts. If 180 days pass with no inspection activity — no passed inspections, no scheduled inspections, nothing in the record showing progress — the building department can declare the permit expired or abandoned. The permit doesn't send you a warning. It simply lapses.

### What "Abandonment" Means in Practice

"Abandonment" is the building department's term, and it confuses contractors because the project often isn't abandoned at all. The crew might be on site. The framing might be up. But here's the critical distinction: **the AHJ measures progress through its own records, not through what you can see from the street.**

In most jurisdictions, "progress" means inspection activity. A passed inspection is a timestamped entry in the department's system proving work is advancing. Without those entries, your busy job site and an empty lot look identical in the permit database. This is why experienced contractors get caught: they were watching the work, but the permit was watching the inspection log, and the two told different stories.

Some cities add a second clock. New York gives permits up to two years (730 days) but still requires work to commence within 12 months. Houston allows two years but voids the permit on the 180th day of inactivity. San Diego gives a one-year utilization period but voids the permit if work doesn't begin within 180 days or stops for 180 days. The details vary, but the 180-day heartbeat underneath is nearly universal.

## What "Expired" Legally Means

An expired permit is not paused, suspended, or "mostly fine." The authorization it granted has ended. Concretely, this means:

- **You cannot legally continue the work.** The permit was the legal basis for construction. Without it, ongoing work is unpermitted work, with all the exposure that carries.
- **You cannot schedule inspections under it.** Inspectors need an active permit to log results against. An expired permit number will be rejected in the system.
- **Prior approvals may not survive.** Approved plans, variances, and fee calculations attached to the original permit may or may not carry forward, depending on the jurisdiction. Some AHJs honor them for a grace period; others start from zero.

The single most important action is to verify the permit's actual status. Check the AHJ's online portal or call the building department. The status is a matter of public record — don't guess.

## The Consequences, in Order

### 1. All Work Must Stop — Immediately

This is non-negotiable. The moment you know (or suspect) a permit has expired, halt work on the affected scope. "Just finishing this one thing" is how a recoverable administrative problem becomes an enforcement case. Every day of work performed under an expired permit is a day of unpermitted work.

### 2. Fines and Penalties

This is where expiration gets expensive fast, because many jurisdictions fine **per day**. Real, verified penalty schedules from major cities:

- **New York City:** building violations carry penalties of **$800 to $4,000 per violation** under the city's official penalty schedule.
