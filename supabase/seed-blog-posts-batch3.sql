A permit that lapsed quietly three weeks ago isn't just an administrative problem — in a daily-fine jurisdiction, it's an accumulating liability. This is the strongest possible argument for discovering expirations early rather than late.

### 3. Stop-Work Orders

If the building department learns that work is continuing under an expired permit — through a complaint, a routine drive-by, or an inspector visit — a stop-work order is the standard response. Everything freezes until the permit issue is resolved and any penalties are addressed. Even the threat of one justifies halting voluntarily the moment you discover the expiration.

### 4. Reapplication Costs

Depending on the jurisdiction and how long the permit has been lapsed, you may need to apply for an entirely new permit — new application, new plan review, new fees at current rates. If the building code has been updated since the original permit was issued, the new application is reviewed under the new code, which can force changes to designs or even to completed work. A lapsed permit that crosses a code cycle is one of the most expensive preventable problems in construction.

## Why Expiration Sneaks Up on Good Contractors

Here's the part nobody tells you: **the building department will not remind you.** Permits don't come with a courtesy call at day 150. The expiration terms are printed on the permit card or in the issuance letter, and then the responsibility is entirely yours.

Expiration sneaks up for unremarkable reasons: the project was delayed and the commencement window closed before work started. Work started but stalled — weather, a subcontractor dispute, a client decision on hold — and no inspections happened for months. The work actually progressed but nobody called for inspections, so the record shows nothing. Or a new contractor took over a half-finished job and inherited a permit closer to expiration than anyone realized.

None of these involve negligence in the craft. They involve busy schedules and deadlines that live on a piece of paper nobody looked at after day one.

## What to Do the Day You Discover It

