Here's the direct answer: **your AHJ is the government body — city, county, town, or special district — that has the legal authority to issue your building permits, enforce the building code, and conduct inspections for a specific project location.** There is no single national AHJ. Every project has one, and it's determined entirely by geography.

## Why the AHJ Concept Exists

Building codes in the United States are adopted and enforced locally. The state may write a model code (or adopt one like the International Building Code), but the actual authority to say "yes, you may build" and "no, fix this" belongs to the local government covering the project site. That local government is the AHJ.

