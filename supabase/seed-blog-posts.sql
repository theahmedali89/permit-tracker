## Who Can Be an AHJ?

The AHJ for your project is typically one of the following:

- **A city building department** — for projects inside incorporated city limits (the most common case for contractors).
- **A county building department** — for projects in unincorporated areas, and in some states, the county plays a larger role overall.
- **A town or village code enforcement office** — common in Northeastern states with strong town-level government.
